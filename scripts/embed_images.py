#!/usr/bin/env python3
"""
Script to embed weapon PNG images as compressed data into C++ header file.
Converts PNG files to RGBA pixel data, compresses with zlib, and generates
cheat/embedded_weapon_data.h for compile-time embedding.
"""

from PIL import Image
import zlib
from pathlib import Path

# Weapon mapping: filename -> C++ identifier
WEAPONS = [
    ("ak", "ak"),
    ("ancientstar", "ancientstar"),  # maps to vega in code
    ("arm", "arm"),
    ("bar95", "bar95"),
    ("defender", "defender"),
    ("dikobraz", "dikobraz"),
    ("fanatic", "fanatic"),
    ("generator", "generator"),
    ("hound", "hound"),
    ("invader", "invader"),
    ("jupiter", "jupiter"),
    ("m4a", "m4a"),
    ("madrabbit", "madrabbit"),
    ("madrat", "madrat"),
    ("mf18", "mf18"),
    ("mg7", "mg7"),
    ("rhino", "rhino"),
    ("stellarwind", "stellarwind"),
    ("ump99", "ump99"),
    ("uzi", "uzi"),
    ("vss", "vss"),
    ("whitedwarf", "whitedwarf"),
]

def process_image(png_path):
    """Load PNG, convert to RGBA, compress with zlib."""
    img = Image.open(png_path).convert("RGBA")
    width, height = img.size
    
    # Get raw RGBA pixel data
    pixel_data = img.tobytes()
    
    # Compress with zlib level 9
    compressed = zlib.compress(pixel_data, level=9)
    
    return width, height, compressed

def format_bytes_as_hex(data, bytes_per_line=16):
    """Format bytes as hex array with specified bytes per line."""
    lines = []
    for i in range(0, len(data), bytes_per_line):
        chunk = data[i:i+bytes_per_line]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_bytes}")
    return ",\n".join(lines)

def generate_header():
    """Generate the C++ header file with embedded weapon data."""
    script_dir = Path(__file__).parent
    repo_root = script_dir.parent
    resources_dir = repo_root / "resources"
    output_path = repo_root / "cheat" / "embedded_weapon_data.h"
    
    header_lines = [
        "// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY",
        "// Generated by scripts/embed_images.py",
        "// Contains compressed weapon icon data embedded at compile-time",
        "",
        "#pragma once",
        "#include <stddef.h>",
        "",
        "namespace EmbeddedWeaponData {",
        ""
    ]
    
    # Process each weapon
    for filename, identifier in WEAPONS:
        png_path = resources_dir / f"{filename}.png"
        
        if not png_path.exists():
            print(f"Warning: {png_path} not found, skipping...")
            continue
        
        print(f"Processing {filename}.png...")
        width, height, compressed = process_image(png_path)
        
        # Add constants and data array for this weapon
        header_lines.append(f"    // {filename}.png ({width}x{height}, compressed: {len(compressed)} bytes)")
        header_lines.append(f"    constexpr unsigned int {identifier}_width = {width};")
        header_lines.append(f"    constexpr unsigned int {identifier}_height = {height};")
        header_lines.append(f"    constexpr size_t {identifier}_compressed_size = {len(compressed)};")
        header_lines.append(f"    static const unsigned char {identifier}_data[] = {{")
        header_lines.append(format_bytes_as_hex(compressed))
        header_lines.append("    };")
        header_lines.append("")
    
    # Close namespace
    header_lines.append("} // namespace EmbeddedWeaponData")
    header_lines.append("")
    
    # Write the header file
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(header_lines))
    
    print(f"Generated {output_path}")

if __name__ == "__main__":
    generate_header()
